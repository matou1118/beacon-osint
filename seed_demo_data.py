def generate_publish_dates(count: int) -> list[str]:
    """生成覆盖5年的发布日期，近期数据更多。"""
    now = datetime.now(timezone.utc)
    dates = []
    # 2026年（当前年）— 最多
    for i in range(count // 3 + 2):
        dates.append((now - timedelta(days=i * 5)).strftime("%Y-%m-%d"))
    # 2025年
    for i in range(count // 4):
        dates.append(f"2025-{(i % 12) + 1:02d}-{(i % 28) + 1:02d}")
    # 2024年
    for i in range(count // 5):
        dates.append(f"2024-{(i % 12) + 1:02d}-{(i % 28) + 1:02d}")
    # 2023年
    for i in range(count // 6):
        dates.append(f"2023-{(i % 12) + 1:02d}-{(i % 28) + 1:02d}")
    # 2022年
    for i in range(count // 8):
        dates.append(f"2022-{(i % 12) + 1:02d}-{(i % 28) + 1:02d}")
    return dates[:count]


def seed_demo_data(db_path: str = "data/beacon.db") -> dict[str, int]:
    """注入演示数据到数据库。"""
    dates = generate_publish_dates(len(DEMO_RECORDS))
    now = utcnow()

    records = []
    for idx, (province, category, title, issuing_body, gov_level) in enumerate(DEMO_RECORDS):
        publish_date = dates[idx % len(dates)]
        source_id = f"demo_{province}_{idx}"
        source_url = f"https://www.gov.cn/demo/{province}/{idx}"
        records.append({
            "source_id": source_id,
            "source_url": source_url,
            "title": title,
            "publish_date": publish_date,
            "content": f"【演示数据】{title}。发布机构：{issuing_body}。发布日期：{publish_date}。",
            "gov_level": gov_level,
            "region_province": province,
            "category_l1": category,
            "issuing_body": issuing_body,
            "fetched_at": now.isoformat(),
            "source_type": "demo",
            "source_priority": 5,
            "cadence_tier": "daily",
        })

    with Database(db_path) as db:
        result = db.upsert_announcements(records)
    return result


def clear_demo_data(db_path: str = "data/beacon.db") -> int:
    """清除所有演示数据（source_id 以 demo_ 开头的记录）。"""
    from sqlalchemy import delete as sa_delete
    from storage.models import Announcement

    with Database(db_path) as db:
        with db.session() as session:
            count = session.execute(
                sa_delete(Announcement).where(Announcement.source_id.like("demo_%"))
            ).rowcount
    return int(count or 0)


def main() -> None:
    parser = argparse.ArgumentParser(description="演示数据注入/清除工具")
    parser.add_argument("--clear", action="store_true", help="清除演示数据")
    parser.add_argument("--db", default="data/beacon.db", help="数据库路径")
    args = parser.parse_args()

    if args.clear:
        deleted = clear_demo_data(args.db)
        print(f"已清除 {deleted} 条演示数据。")
    else:
        result = seed_demo_data(args.db)
        print(f"演示数据注入完成：新增 {result['inserted']} 条，更新 {result['updated']} 条，未变 {result['unchanged']} 条。")
        print(f"覆盖 {len(set(r[0] for r in DEMO_RECORDS))} 个省份，{len(set(r[1] for r in DEMO_RECORDS))} 个分类。")


if __name__ == "__main__":
    main()
